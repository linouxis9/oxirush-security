//! What the benchmarks of oxirush-security run on.

/// Octets that look random and are the same at every run, so that no
/// algorithm finds a pattern in its message and two runs measure the same
/// thing.
pub fn message(octets: usize) -> Vec<u8> {
    let mut state = 0x9e37_79b9_7f4a_7c15u64;
    (0..octets)
        .map(|_| {
            state ^= state << 13;
            state ^= state >> 7;
            state ^= state << 17;
            (state >> 32) as u8
        })
        .collect()
}

